/** Etiqueta de una subcategoria en el idioma de la pagina. */
export function subcategoryLabel(slug: string, lang: "en" | "es"): string {
  if (!slug) return slug;
  if (lang === "es") {
    const es = SUBCATEGORY_LABEL_ES[slug];
    if (es) return es;
    const plain = slug.replace(/_/g, " ").trim();
    return plain.charAt(0).toUpperCase() + plain.slice(1);
  }
  return SUBCATEGORY_LABEL_EN[slug] ?? humanize(slug);
}
