/* Metadata for a static marketing page. `pathOverride` lets dynamic
 * children (collections/[id]) keep their own canonical. */
export function pageMetadata(key: SeoPageKey, locale: Locale, pathOverride?: string): Metadata {
  const page = PAGE_SEO[key];
  const copy = page.copy[locale];
  return buildMetadata({
    locale,
    path: pathOverride ?? page.path,
    title: copy.title,
    description: copy.description,
    noIndex: page.noIndex,
  });
}
