import type { Metadata } from "next";
import { DEFAULT_LOCALE, LOCALES, isLocale, type Locale } from "@/i18n/config";

/* SEO helper for the marketing surface.
 *
 * Single source of truth for:
 *   - the canonical site origin (siteUrl)
 *   - the per-page, per-locale title + description copy (PAGE_SEO)
 *   - the Metadata shape every localized page ships: absolute canonical,
 *     hreflang alternates (en, es, x-default), Open Graph and Twitter card.
 *
 * Pages call pageMetadata("pricing", locale) for the static ones or
 * buildMetadata({...}) when the copy comes from data (learn/[slug],
 * prompts/[id]).
 *
 * Domain decision D6 (10 sep 2026): the canonical origin is
 * https://creative.artostudio.ai. NEXT_PUBLIC_SITE_URL overrides it (set in
 * Vercel prod); anything else (legacy vercel.app host, library.artostudio.ai)
 * is 301'd by next.config.ts.
 */

export const DEFAULT_SITE_URL = "https://creative.artostudio.ai";
export const SITE_NAME = "ARTO Studio AI";

/* Request header src/proxy.ts sets with the resolved locale so the root
 * layout (which sits above [locale]) can render <html lang>. */
export const LOCALE_HEADER = "x-locale";

/* Path of the global Open Graph image generated by
 * src/app/opengraph-image.tsx (next/og, 1200x630). */
export const DEFAULT_OG_IMAGE_PATH = "/opengraph-image";

const OG_LOCALE: Record<Locale, string> = { en: "en_US", es: "es_MX" };

export function siteUrl(): string {
  const raw = process.env.NEXT_PUBLIC_SITE_URL?.trim();
  const base = raw && /^https?:\/\//i.test(raw) ? raw : DEFAULT_SITE_URL;
  return base.replace(/\/+$/, "");
}

/* Narrow an unknown [locale] param to a Locale, falling back to the default.
 * Pages already 404 on bad locales in their body; metadata just needs a
 * safe value. */
export function localeOf(value: unknown): Locale {
  return isLocale(value) ? value : DEFAULT_LOCALE;
}

/* "/pricing/" -> "/pricing", "pricing" -> "/pricing", "" -> "/". Drops any
 * query string so canonicals never carry filters. */
function normalizePath(path: string): string {
  const noQuery = path.split(/[?#]/)[0] ?? "";
  const withSlash = noQuery.startsWith("/") ? noQuery : `/${noQuery}`;
  const trimmed = withSlash.replace(/\/+$/, "");
  return trimmed === "" ? "/" : trimmed;
}

/* "/pricing" + "es" -> "/es/pricing"; "/" + "en" -> "/en". */
export function localizedPath(locale: Locale, path: string): string {
  const p = normalizePath(path);
  return `/${locale}${p === "/" ? "" : p}`;
}

export function absoluteUrl(path: string): string {
  return `${siteUrl()}${normalizePath(path)}`;
}

/* Append the brand suffix unless the title already carries it. Used for
 * data-driven titles (learn/[slug], prompts/[id]). */
export function withBrand(title: string): string {
  const clean = title.trim();
  if (clean.toLowerCase().includes(SITE_NAME.toLowerCase())) return clean;
  return `${clean} · ${SITE_NAME}`;
}

/* Trim a description to a search-snippet friendly length on a word boundary. */
export function clampDescription(text: string, max = 155): string {
  const clean = text.replace(/\s+/g, " ").trim();
  if (clean.length <= max) return clean;
  const cut = clean.slice(0, max);
  const lastSpace = cut.lastIndexOf(" ");
  return `${(lastSpace > 80 ? cut.slice(0, lastSpace) : cut).replace(/[\s,.;:]+$/, "")}...`;
}

export interface BuildMetadataInput {
  locale: Locale;
  /* Path WITHOUT the locale prefix, e.g. "/pricing" or "/prompts/br-001". */
  path: string;
  title: string;
  description: string;
  /* Site-relative or absolute image URL. Omit for the global OG image.
   * Pass null to set no image via config so the segment's own file-based
   * opengraph-image.tsx / twitter-image.tsx apply (Next only merges the
   * file-based image when the config does not define `images`). */
  ogImage?: string | null;
  noIndex?: boolean;
}

export function buildMetadata(input: BuildMetadataInput): Metadata {
  const { locale, path, title, description, ogImage, noIndex } = input;
  const site = siteUrl();
  const canonical = `${site}${localizedPath(locale, path)}`;

  const languages: Record<string, string> = {};
  for (const l of LOCALES) languages[l] = `${site}${localizedPath(l, path)}`;
  languages["x-default"] = `${site}${localizedPath(DEFAULT_LOCALE, path)}`;

  const imageUrl =
    ogImage === null
      ? null
      : /^https?:\/\//i.test(ogImage ?? "")
        ? (ogImage as string)
        : absoluteUrl(ogImage ?? DEFAULT_OG_IMAGE_PATH);

  const metadata: Metadata = {
    title,
    description,
    alternates: { canonical, languages },
    openGraph: {
      type: "website",
      siteName: SITE_NAME,
      locale: OG_LOCALE[locale],
      alternateLocale: LOCALES.filter((l) => l !== locale).map((l) => OG_LOCALE[l]),
      url: canonical,
      title,
      description,
      ...(imageUrl ? { images: [{ url: imageUrl, width: 1200, height: 630, alt: title }] } : {}),
    },
    twitter: {
      card: "summary_large_image",
      title,
      description,
      ...(imageUrl ? { images: [imageUrl] } : {}),
    },
  };

  if (noIndex) metadata.robots = { index: false, follow: false };
  return metadata;
}

